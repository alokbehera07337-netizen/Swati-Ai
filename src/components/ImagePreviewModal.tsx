import { Download, X } from "lucide-react";
import type { LanguageMode } from "../types";

interface ImagePreviewModalProps {
  imageUrl: string | null;
  prompt?: string;
  language: LanguageMode;
  onDownload: (imageUrl: string, prompt?: string) => void;
  onClose: () => void;
}

export function ImagePreviewModal({
  imageUrl,
  prompt,
  language,
  onDownload,
  onClose,
}: ImagePreviewModalProps) {
  if (!imageUrl) return null;

  const isHindi = language === "hi";
  const isOdia = language === "or";

  return (
    <div
      role="dialog"
      aria-modal="true"
      aria-label={
        isOdia
          ? "ଛବି ପ୍ରିଭ୍ୟୁ"
          : isHindi
            ? "तस्वीर पूर्वावलोकन"
            : "Image preview"
      }
      className="fixed inset-0 z-50 flex flex-col bg-black/90 backdrop-blur-md"
    >
      <div className="pt-safe px-4 h-16 flex items-center justify-between gap-3 border-b border-slate-800/80 shrink-0">
        <p className="text-sm font-medium text-slate-200 truncate">
          {prompt ||
            (isOdia
              ? "SWATI AI ଦ୍ୱାରା ନିର୍ମିତ ଛବି"
              : isHindi
                ? "SWATI AI द्वारा निर्मित तस्वीर"
                : "Generated by SWATI AI")}
        </p>

        <div className="flex items-center gap-2 shrink-0">
          <button
            type="button"
            onClick={() => onDownload(imageUrl, prompt)}
            className="min-h-[44px] px-4 rounded-xl bg-blue-600 hover:bg-blue-500 active:scale-95 text-white text-sm font-medium flex items-center gap-2 transition-all cursor-pointer"
          >
            <Download className="w-4 h-4" />
            <span>
              {isOdia ? "ଡାଉନଲୋଡ୍" : isHindi ? "डाउनलोड" : "Download"}
            </span>
          </button>

          <button
            type="button"
            onClick={onClose}
            aria-label={
              isOdia
                ? "ପ୍ରିଭ୍ୟୁ ବନ୍ଦ କରନ୍ତୁ"
                : isHindi
                  ? "पूर्वावलोकन बंद करें"
                  : "Close preview"
            }
            className="min-h-[44px] min-w-[44px] flex items-center justify-center rounded-xl bg-slate-800/80 hover:bg-slate-700 text-slate-200 transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>
      </div>

      <div
        onClick={onClose}
        className="flex-1 min-h-0 flex items-center justify-center p-4 sm:p-8 cursor-zoom-out"
      >
        <img
          src={imageUrl}
          alt={prompt || "Generated AI image"}
          referrerPolicy="no-referrer"
          onClick={(e) => e.stopPropagation()}
          className="max-w-full max-h-full rounded-2xl object-contain border border-blue-500/20 shadow-2xl cursor-default"
        />
      </div>
    </div>
  );
}
